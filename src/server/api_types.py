#!/usr/bin/env python3
"""The page's TypeScript types, from the API's own description (api/models.py, by way of FastAPI's
OpenAPI): writes web/src/api/schema.ts. `npm run api-types` in web runs it; tests/test_web.py
fails while what is committed is not what it writes.

Ours rather than openapi-typescript, which needs TypeScript 5's compiler API (web is on 7, which
has none), and the schemas are few in kind: objects, enums and constants, arrays, maps, refs and
nullable ones. A field may say its TypeScript type itself (`tsType`), for JSON of any shape.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WEB_API = HERE.parent.parent / "web/src/api"
HEADER = ("// Generated by src/server/api_types.py from the API's description (src/server/api/models.py): do not\n"
          "// edit, run `npm run api-types` in web. What the routes take and answer; web/src/api/types.ts names them.\n"
          "\n/** JSON of any shape: what a field takes that the API does not look into. */\n"
          "export type Json = string | number | boolean | null | Json[] | { [key: string]: Json };\n"
          "export type JsonObject = { [key: string]: Json };\n")
SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def ts(schema):
    """A schema as a TypeScript type."""
    if "tsType" in schema:
        return schema["tsType"]
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts(s) for s in schema["anyOf"]))
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        item = ts(schema.get("items", {}))
        return f"({item})[]" if " " in item else f"{item}[]"
    if kind == "object" and "properties" not in schema:
        values = schema.get("additionalProperties", True)
        return f"Record<string, {'unknown' if values is True else ts(values)}>"
    return SCALARS.get(kind, "unknown")


def doc(text, indent=""):
    lines = text.strip().splitlines()
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {line}".rstrip() + "\n" for line in lines) + f"{indent} */\n"


def interface(name, schema):
    out = doc(schema["description"]) if schema.get("description") else ""
    if "properties" not in schema:
        return out + f"export type {name} = {ts(schema)};\n"
    out += f"export interface {name} {{\n"
    required = set(schema.get("required", []))
    for field, spec in schema["properties"].items():
        if spec.get("description"):
            out += doc(spec["description"], "  ")
        key = field if re.fullmatch(r"[A-Za-z_$][\w$]*", field) else json.dumps(field)
        out += f"  {key}{'' if field in required else '?'}: {ts(spec)};\n"
    if schema.get("additionalProperties") is True:
        out += "  [key: string]: unknown;\n"
    return out + "}\n"


def schema_ts(spec):
    return HEADER + "".join("\n" + interface(name, schema) for name, schema in spec["components"]["schemas"].items())


def openapi():
    sys.path.insert(0, str(HERE))
    from api.app import app  # noqa: E402
    return app.openapi()


def generated():
    """What schema.ts should hold."""
    return schema_ts(openapi())


if __name__ == "__main__":
    (WEB_API / "schema.ts").write_text(generated())
    print(f"wrote {WEB_API / 'schema.ts'}")
